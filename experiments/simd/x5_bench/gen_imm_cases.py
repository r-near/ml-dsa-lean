#!/usr/bin/env python3
"""Generate src/imm_cases.rs: one differential-test call per immediate operand value."""
from pathlib import Path
out = ["// Generated by gen_imm_cases.py. Do not edit.", "use crate::*;", "pub fn run_imm_cases(rng: &mut crate::Rng) {"]
for m in range(256):
    out.append(f"    t_shuffle::<{m}>(rng);")
for m in range(256):
    out.append(f"    t_permute4x64::<{m}>(rng);")
for m in range(256):
    out.append(f"    t_blend::<{m}>(rng);")
for m in list(range(0, 64)) + [64, 100]:
    out.append(f"    t_srli::<{m}>(rng);")
for m in list(range(0, 32)) + [32, 100]:
    out.append(f"    t_srai::<{m}>(rng);")
imms = [lo | (hi << 4) for lo in list(range(4)) + [8, 9] for hi in list(range(4)) + [8, 10]]
for m in imms:
    out.append(f"    t_perm2x128::<{m}>(rng);")
out.append("}")
Path(__file__).resolve().parent.joinpath("src/imm_cases.rs").write_text("\n".join(out) + "\n")
print("immediates:", 256 * 3 + 66 + 34 + len(imms))
