#!/usr/bin/env python3
"""Regenerate src/tables.rs from the ZETAS table in src/ntt.rs (the copy of the crate's own table)."""
import re, sys
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here / "src/ntt.rs").read_text()
body = re.search(r"pub const ZETAS: \[u32; 256\] = \[(.*?)\];", src, re.S).group(1)
Z = [int(x) for x in re.findall(r"\d+", body)]
assert len(Z) == 256
Q = 8380417
QINV = pow(Q, -1, 2**32)  # q^-1 mod 2^32
assert (Q * QINV) % 2**32 == 1

shoup = [(z << 32) // Q for z in Z]  # floor(z * 2^32 / q)
mont = []
for z in Z:
    v = (z << 32) % Q
    mont.append(v - Q if v > Q // 2 else v)  # centered, |v| <= (q-1)/2
assert all(abs(v) <= (Q - 1) // 2 for v in mont)

def arr(name, ty, vals):
    rows = []
    for i in range(0, 256, 8):
        rows.append("    " + ", ".join(str(v) for v in vals[i:i + 8]) + ",")
    return f"pub const {name}: [{ty}; 256] = [\n" + "\n".join(rows) + "\n];\n"

neg = [(Q - z) % Q for z in Z]            # sub(0, z) as used by the inverse NTT
neg_shoup = [(n << 32) // Q for n in neg]
F = 8347681                               # 256^-1 mod q
assert (F * 256) % Q == 1
F_SHOUP = (F << 32) // Q

out = "// Generated by gen_tables.py from ZETAS in src/ntt.rs. Do not edit.\n"
out += f"/// q^-1 mod 2^32 (as the i32 bit pattern used by Montgomery reduction).\npub const QINV: i32 = {QINV if QINV < 2**31 else QINV - 2**32};\n"
out += "/// floor(ZETAS[k] * 2^32 / q): Shoup companion of each zeta.\n" + arr("ZETAS_SHOUP", "u32", shoup)
out += "/// ZETAS[k] * 2^32 mod q, centered into [-(q-1)/2, (q-1)/2].\n" + arr("ZETAS_MONT", "i32", mont)
out += "/// floor((q - ZETAS[k]) * 2^32 / q): Shoup companion of the negated zetas used by the inverse NTT.\n" + arr("ZETAS_NEG_SHOUP", "u32", neg_shoup)
out += f"/// floor(256^-1 * 2^32 / q): Shoup companion of the inverse-NTT scale factor 8_347_681.\npub const F_SHOUP: u32 = {F_SHOUP};\n"
out += f"/// 2^64 mod q (second factor of the two-reduction Montgomery product).\npub const R2: u64 = {pow(2, 64, Q)};\n"
(here / "src/tables.rs").write_text(out)
print("wrote", here / "src/tables.rs", "QINV", QINV)
