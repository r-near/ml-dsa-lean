#!/usr/bin/env bash
# Done-gate for the non-vacuity witnesses (run on Linux): build the TopWitness modules, which the default
# build roots (lean/Proofs.lean) do not import, fail on any build error or `sorry`, then run the axiom check on the
# names in lean/witness-theorems.txt, then the whole-environment scan for forbidden declarations over every module (the
# default targets are built too). Exit 0 only if all pass and the default roots stay free of the witnesses.
# Usage: scripts/witness-check.sh [Module ...]   (default: Proofs.TopWitnessCorrect, which imports the whole chain)
# The kernel evaluations are the cost, and they are split into small pieces (scripts/gen-witness-stages.py), so the check
# fits the free 4 vCPU / 16 GB `ubuntu-latest` runner. Measured cold in an Ubuntu 24.04 container with `--memory 16g
# --memory-swap 16g` and 4 pinned cores (2026-11-12): LEAN_NUM_THREADS=1 8195 s, 10.2 GB of anonymous memory at most;
# LEAN_NUM_THREADS=2 7187 s, 12.9 GB. Before the split it needed about 46 GB (24 GB for the largest declaration). Run it as a
# long background job (.github/workflows/lean.yml runs it weekly and on manual dispatch).
# The stage modules TopWitness{KA,KS,Nf*,Ni,Nc*,Misc} are generated by scripts/gen-witness-stages.py; the first step
# below regenerates them into a temporary directory and fails on any difference from the committed files.
set -euo pipefail
cd "$(dirname "$0")/../lean"
export PATH="$HOME/.elan/bin:$PATH"
if grep -nE '^import +Proofs\.TopWitness' Proofs.lean; then
  echo "WITNESS CHECK FAIL: Proofs.lean imports a TopWitness module (it must stay out of the default build)"; exit 1
fi
python3 -I ../scripts/gen-witness-stages.py --check || { echo "WITNESS CHECK FAIL: stage modules differ from scripts/gen-witness-stages.py"; exit 1; }
mkdir -p .lake
SEED="${LEAN_PACKAGES_SEED:-}"
if [ ! -d .lake/packages ] && [ -n "$SEED" ] && [ -d "$SEED" ]; then cp -a "$SEED" .lake/packages; fi
lake exe cache get >/dev/null 2>&1 || true
[ $# -gt 0 ] || set -- Proofs.TopWitnessCorrect
rc=0
timeout 18000 lake build "$@" 2>&1 | tee .lake/witness-build.log || rc=$?
if [ "$rc" -ne 0 ]; then echo "WITNESS CHECK FAIL: lake build exited $rc"; exit 1; fi
if grep -nE "(^|[^a-z])error:|declaration uses 'sorry'" .lake/witness-build.log; then
  echo "WITNESS CHECK FAIL: errors or sorry in the build log"; exit 1
fi
cd ..
scripts/check-axioms.sh --list witness-theorems.txt --no-impl
# Every module of lean/Impl, lean/Spec and lean/Proofs must have an .olean for the whole-environment scan to cover it
# (scripts/lean-check.sh scans the default roots; the TopWitness modules are built above). The default targets are built here
# too, which is a no-op after scripts/lean-check.sh and the full build otherwise.
cd lean
rc=0
timeout 18000 lake build Impl Spec Proofs 2>&1 | tee .lake/witness-default-build.log || rc=$?
if [ "$rc" -ne 0 ]; then echo "WITNESS CHECK FAIL: lake build of the default targets exited $rc"; exit 1; fi
if grep -nE "(^|[^a-z])error:|declaration uses 'sorry'" .lake/witness-default-build.log; then
  echo "WITNESS CHECK FAIL: errors or sorry in the build log of the default targets"; exit 1
fi
cd ..
scripts/check-no-decls.sh --all-built
echo "WITNESS CHECK OK: $*"
