# Generates the stage modules lean/Proofs/TopWitness{KA,KS,Nf1,Nf2,Ni,Nc1,Nc2,Nc3,Misc}.lean (run from lean/).
#
# Each heavy kernel evaluation (an NTT, an inverse NTT, SHAKE256 on a long message, a rounding or hash of a vector) is
# checked piece by piece, so that no single kernel check needs more than about 8 GB: one theorem per piece, each against the
# literal values at the piece boundaries printed by lean/SpecTests/WitnessMidGen.lean (lean/Proofs/TopWitnessMid.lean), and
# the stage lemma itself, with its statement unchanged, assembled from the pieces by the lemmas of lean/Proofs/TopWitnessPieces.lean.
# The cut lists below must equal the ones in lean/SpecTests/WitnessMidGen.lean.
# Usage: python3 -I ../scripts/gen-witness-stages.py [dev|--check]
#   (no argument)  write the modules with `by decide +kernel`.
#   dev            write `by sorry` instead: quick elaboration checks only, never commit that output.
#   --check        regenerate into a temporary directory and compare byte for byte with the committed modules; exit 1
#                  on any difference. scripts/witness-check.sh runs this first, so a hand edit of a stage module, or
#                  a change of this script without regenerating, fails the witness gate.
import filecmp, os, sys, tempfile
args = sys.argv[1:]
if len(args) > 1 or (args and args[0] not in ('dev', '--check')):
    sys.exit("usage: gen-witness-stages.py [dev|--check]")
dev = args == ['dev']
check = args == ['--check']
PR = "by sorry" if dev else "by decide +kernel"
FWD_CUTS = [2, 4, 6]       # forward NTT: pieces of 2 layers (8 layers in all)
INV_CUTS = [2, 4, 6, 8]    # inverse NTT: pieces of 2 layers, then the scaling by 256^-1 (and whatever follows) as its own piece
TR_CUTS = [3, 6, 9]        # H(pk, 64): 10 blocks of SHAKE256, pieces of 3 permutations
CT_CUTS = [3, 6]           # H(mu || w1, lam/4): 7 blocks
GEN = ("-- GENERATED by scripts/gen-witness-stages.py (run from lean/); do not edit by hand.\n"
       "-- Verify with `python3 -I ../scripts/gen-witness-stages.py --check`, which scripts/witness-check.sh runs.\n")
def hdr(extra_imports, doc):
    return (GEN + "import Proofs.TopWitnessLit\n" + "".join(f"import {m}\n" for m in extra_imports) +
            f"\n/-!\n{doc}\n-/\n\nopen Spec\n\nnamespace Proofs\nnamespace TopWitness\n\n")
def thm(name, stmt, doc):
    return (f"set_option maxRecDepth 100000 in\nset_option maxHeartbeats 4000000 in\n/-- {doc} -/\n"
            f"theorem {name} :\n    {stmt} := {PR}\n\n")
END = "end TopWitness\nend Proofs\n"
files = {}

def thm_with(name, stmt, doc, proof):
    """A stage lemma whose proof is the glue of the pieces (a list of tactic lines, or a term)."""
    if isinstance(proof, list):
        proof = "by\n" + "\n".join("    " + t for t in proof)
    return (f"set_option maxRecDepth 100000 in\nset_option maxHeartbeats 4000000 in\n/-- {doc} -/\n"
            f"theorem {name} :\n    {stmt} := {proof}\n\n")

def fwd_ntt(name, X, tag, R, what):
    """NTT X = Pl Data.R, checked in pieces of FWD_CUTS layers."""
    b = [0] + FWD_CUTS + [8]
    out, pn = "", []
    for j in range(len(b) - 1):
        a, c = b[j], b[j + 1]
        inp = f"({X}, 0)" if a == 0 else f"(Pl Mid.nf_{tag}_c{a}, {2 ** a - 1})"
        stmt = (f"(fwdLayers {a} 8 {inp}).1 = Pl Data.{R}" if c == 8
                else f"fwdLayers {a} {c} {inp} = (Pl Mid.nf_{tag}_c{c}, {2 ** c - 1})")
        out += thm(f"{name}_p{j + 1}", stmt, f"Layers {a} to {c - 1} of the forward NTT of {what}.")
        pn.append(f"{name}_p{j + 1}")
    splits = [f"fwdLayers_split {b[j]} {b[j + 1]} 8 (by omega) (by omega) _" for j in range(len(b) - 2)]
    proof = ["rw [NTT_eq_fwdLayers]", "rw [" + ", ".join(splits) + "]", "rw [" + ", ".join(pn[:-1]) + "]", f"exact {pn[-1]}"]
    return out, proof

def inv_ntt(name, X, tag, R, what, tail="", pre=""):
    """NTTInv X (+ tail) = Pl Data.R, checked in pieces of INV_CUTS layers and the scaling."""
    b = [0] + INV_CUTS
    out, pn = "", []
    for j in range(len(b) - 1):
        a, c = b[j], b[j + 1]
        inp = f"({X}, 256)" if a == 0 else f"(Pl Mid.ni_{tag}_c{a}, {256 >> a})"
        out += thm(f"{name}_p{j + 1}", f"invLayers {a} {c} {inp} = (Pl Mid.ni_{tag}_c{c}, {256 >> c})",
                   f"Layers {a} to {c - 1} of the inverse NTT of {what}.")
        pn.append(f"{name}_p{j + 1}")
    out += thm(f"{name}_p{len(b)}", f"invScale (Pl Mid.ni_{tag}_c8){tail} = Pl Data.{R}",
               f"The scaling by `256⁻¹` of the inverse NTT of {what}" + (", and the sum." if tail else "."))
    pn.append(f"{name}_p{len(b)}")
    splits = [f"invLayers_split {b[j]} {b[j + 1]} 8 (by omega) (by omega) _" for j in range(len(b) - 2)]
    proof = (([f"rw [{pre.rstrip(', ')}]"] if pre else []) + ["rw [NTTInv_eq_invLayers]", "rw [" + ", ".join(splits) + "]",
             "rw [" + ", ".join(pn[:-1]) + "]", f"exact {pn[-1]}"])
    return out, proof

# KA: ExpandA entries
s = hdr(["Proofs.SampleA", "Proofs.TopWitnessPieces"], "# `RejNTTPoly` on the 16 seeds of `ExpandA` (ML-DSA-44, `ρ = rhoS`), with the sampled polynomials named\n\nOne kernel evaluation each (the floor of the witnesses: about 10 GB). `Data.a_r_s` are native candidates; the kernel checks them.")
for r in range(4):
    for t in range(4):
        s += thm_with(f"rejA_{r}_{t}", f"Spec.RejNTTPoly 512 (SampleA.pSeed rhoS {r} {t}) = some (Pl Data.a_{r}_{t})",
                      f"Entry `({r}, {t})` of `Â`. The kernel compares the coefficients as natural numbers (`opt_eq_Pl_of_vals`).",
                      "by sorry" if dev else "opt_eq_Pl_of_vals _ _ (by decide +kernel) (by decide +kernel)")
files["TopWitnessKA"] = s + END

# KS: ExpandS entries (imports KA only to schedule the heavy modules one after another)
s = hdr(["Proofs.TopWitnessKA"], "# `RejBoundedPoly` on the 8 seeds of `ExpandS` (ML-DSA-44, `ρ′ = rho1S`), with the sampled polynomials named")
for r in range(4):
    s += thm(f"rejS_{r}", f"Spec.RejBoundedPoly Spec.ML_DSA_44 512 (rho1S ++ IntegerToBytes {r} 2) = some (Rl Data.s1_{r})", f"`s₁[{r}]`.")
for r in range(4):
    s += thm(f"rejS_{r+4}", f"Spec.RejBoundedPoly Spec.ML_DSA_44 512 (rho1S ++ IntegerToBytes {r+4} 2) = some (Rl Data.s2_{r})", f"`s₂[{r}]`.")
files["TopWitnessKS"] = s + END

# The heavy modules form one chain, KA < KS < Misc < Nf1 < Nf2 < Ni < Nc1 < Nc2 < Nc3, by their imports: the imports of
# an earlier module only schedule the later one after it, so that at most one of them is being checked at a time.
NTT_IMPORTS = ["Proofs.TopWitnessPieces", "Proofs.TopWitnessMid"]
FWD_NOTE = "Each `NTT` is checked in four pieces of two layers (`Mid.nf_*` are the polynomials between the pieces)."

# Nf1: forward NTT of s1, s2
s = hdr(["Proofs.TopWitnessMisc"] + NTT_IMPORTS, "# Forward NTTs (kernel stage lemmas): `ŝ₁`, `ŝ₂`\n\n" + FWD_NOTE)
for i in range(4):
    pcs, pf = fwd_ntt(f"nttF_s1_{i}", f"RPoly.toZq (Rl Data.s1_{i})", f"s1_{i}", f"s1h_{i}", f"`s₁[{i}]`")
    s += pcs + thm_with(f"nttF_s1_{i}", f"NTT (RPoly.toZq (Rl Data.s1_{i})) = Pl Data.s1h_{i}", f"`NTT(s₁[{i}])`.", pf)
for i in range(4):
    pcs, pf = fwd_ntt(f"nttF_s2_{i}", f"RPoly.toZq (Rl Data.s2_{i})", f"s2_{i}", f"s2h_{i}", f"`s₂[{i}]`")
    s += pcs + thm_with(f"nttF_s2_{i}", f"NTT (RPoly.toZq (Rl Data.s2_{i})) = Pl Data.s2h_{i}", f"`NTT(s₂[{i}])`.", pf)
files["TopWitnessNf1"] = s + END

# Nf2: forward NTT of t0, y, c
s = hdr(["Proofs.TopWitnessNf1"] + NTT_IMPORTS, "# Forward NTTs (kernel stage lemmas): `t̂₀`, `NTT(y)`, `ĉ`\n\n" + FWD_NOTE)
for i in range(4):
    pcs, pf = fwd_ntt(f"nttF_t0_{i}", f"RPoly.toZq (Rl Data.t0_{i})", f"t0_{i}", f"t0h_{i}", f"`t₀[{i}]`")
    s += pcs + thm_with(f"nttF_t0_{i}", f"NTT (RPoly.toZq (Rl Data.t0_{i})) = Pl Data.t0h_{i}", f"`NTT(t₀[{i}])`.", pf)
for i in range(4):
    pcs, pf = fwd_ntt(f"nttF_y_{i}", f"Pl Data.y_{i}", f"y_{i}", f"yh_{i}", f"`y[{i}]`")
    s += pcs + thm_with(f"nttF_y_{i}", f"NTT (Pl Data.y_{i}) = Pl Data.yh_{i}", f"`NTT(y[{i}])`.", pf)
pcs, pf = fwd_ntt("nttF_c", "RPoly.toZq (Rl Data.cL)", "c", "ch", "`c`")
s += pcs + thm_with("nttF_c", "NTT (RPoly.toZq (Rl Data.cL)) = Pl Data.ch", "`ĉ = NTT(c)`.", pf)
files["TopWitnessNf2"] = s + END

INV_NOTE = ("Each `NTTInv` is checked in five pieces: four of two layers and the scaling by `256⁻¹` (`Mid.ni_*` are the polynomials "
            "between the pieces).")
# Ni: inverse NTT for t and w
s = hdr(["Proofs.TopWitnessNf2"] + NTT_IMPORTS, "# Inverse NTTs (kernel stage lemmas): `t = NTT⁻¹(Â ŝ₁) + s₂` of KeyGen, `w = NTT⁻¹(Â NTT(y))` of Sign\n\n" + INV_NOTE)
for i in range(4):
    tail = f" + RPoly.toZq (Rl Data.s2_{i})"
    pcs, pf = inv_ntt(f"nttI_t_{i}", f"Pl Data.mv_{i}", f"t_{i}", f"t_{i}", f"`Â ŝ₁` in row {i}", tail=tail)
    s += pcs + thm_with(f"nttI_t_{i}", f"NTTInv (Pl Data.mv_{i}) + RPoly.toZq (Rl Data.s2_{i}) = Pl Data.t_{i}", f"`t[{i}]`.", pf)
for i in range(4):
    pcs, pf = inv_ntt(f"nttI_w_{i}", f"Pl Data.wmv_{i}", f"w_{i}", f"w_{i}", f"`Â NTT(y)` in row {i}")
    s += pcs + thm_with(f"nttI_w_{i}", f"NTTInv (Pl Data.wmv_{i}) = Pl Data.w_{i}", f"`w[{i}]`.", pf)
files["TopWitnessNi"] = s + END

def prod(a, b): return f"Vector.zipWith (· * ·) (Pl Data.{a}) (Pl Data.{b})"
prev = "Proofs.TopWitnessNi"
for name, tag, src in [("TopWitnessNc1", "cs1", "s1h"), ("TopWitnessNc2", "cs2", "s2h"), ("TopWitnessNc3", "ct0", "t0h")]:
    s = hdr([prev] + NTT_IMPORTS, f"# Inverse NTTs of `ĉ ∘ ·` (kernel stage lemmas): `{tag}`\n\n" + INV_NOTE +
            " The pointwise product is taken on the coefficient lists (`Pl_mul`).")
    for i in range(4):
        pre = f"Pl_mul Data.ch Data.{src}_{i} (by decide +kernel) (by decide +kernel), "
        pcs, pf = inv_ntt(f"nttI_{tag}_{i}", f"Pl (mulL Data.ch Data.{src}_{i})", f"{tag}_{i}", f"{tag}_{i}",
                          f"`ĉ ∘ {src}[{i}]`", pre=pre)
        s += pcs + thm_with(f"nttI_{tag}_{i}", f"NTTInv ({prod('ch', f'{src}_{i}')}) = Pl Data.{tag}_{i}", f"`{tag}[{i}]`.", pf)
    files[name] = s + END
    prev = "Proofs." + name

# Misc: the cheaper kernel stage lemmas
s = hdr(["Proofs.TopWitnessKS", "Proofs.TopWitnessFast"] + NTT_IMPORTS,
        "# Cheaper kernel stage lemmas of the witnesses (matrix-vector products, rounding, hashes, packing)\n\n"
        "The matrix-vector products are evaluated on the coefficient lists (`Pl_mul`, `Pl_add`, `MatrixVectorNTTF_v4`), the "
        "rounding one polynomial at a time and the two long hashes (`H(pk, 64)`, `H(μ ‖ w1, λ/4)`) a few Keccak permutations "
        "at a time (`absorbFrom_cut`).")
def mv_proof(M, V, R, vs):
    rows = []
    for i in range(4):
        a = " ".join(f"Data.a_{i}_{j}" for j in range(4))
        x = " ".join(f"Data.{vs}_{j}" for j in range(4))
        rows.append(f"(by rw [row4_Pl {a} {x} (by decide +kernel)]; exact congrArg Pl (by decide +kernel))")
    args = " ".join(["_"] * 20)
    return ["rw [MatrixVectorNTT_fast]", f"unfold {M} {V} {R}", f"refine (MatrixVectorNTTF_v4 {args}).trans ?_",
            "exact v4_ext"] + ["  " + r for r in rows]
s += thm_with("mv_lit", "Spec.MatrixVectorNTT Av S1hv = MVv", "`Â ∘ ŝ₁` (KeyGen step 5).", mv_proof("Av", "S1hv", "MVv", "s1h"))
for i in range(4):
    s += thm(f"p2r_lit_p{i}", f"((Pl Data.t_{i}).map (fun x => (Power2Round Spec.ML_DSA_44 x).1), (Pl Data.t_{i}).map (fun x => (Power2Round Spec.ML_DSA_44 x).2)) = (Rl Data.t1_{i}, Rl Data.t0_{i})",
             f"`Power2Round` of `t[{i}]`.")
s += thm_with("p2r_lit", "Spec.Power2RoundVec Spec.ML_DSA_44 Tv = (T1v, T0v)", "KeyGen step 6.",
              ["unfold Tv T1v T0v", "exact Power2RoundVec_v4 _ _ _ _ _ _ _ _ _ _ _ _ _ p2r_lit_p0 p2r_lit_p1 p2r_lit_p2 p2r_lit_p3"])
s += thm("pk_lit", "pkEncodeF Spec.ML_DSA_44 rhoS T1v = Data.pkL", "The public key (`pkEncode` with the fast packing).")

def sponge(name, M, d, N, cuts, tag, out, what):
    """Spec.H M d = out, with the N blocks of pad101 136 M cut after the block counts in `cuts`."""
    P = f"(Keccak.pad101 136 {M})"
    b = [0] + cuts
    txt, pn = "", []
    for j in range(len(b)):
        a = b[j]
        c = b[j + 1] if j + 1 < len(b) else N
        inp = "Keccak.zeroState" if a == 0 else f"(stOf Mid.h_{tag}_c{a})"
        if j + 1 < len(b):
            stmt = f"absorbFrom 136 {P} {a} {c - a} {inp} = stOf Mid.h_{tag}_c{c}"
        else:
            stmt = f"Keccak.squeeze 136 ({d}) (absorbFrom 136 {P} {a} {c - a} {inp}) = {out}"
        txt += thm(f"{name}_p{j + 1}", stmt, f"Blocks {a} to {c - 1} of the absorption in {what}" + (", then the squeeze." if j + 1 == len(b) else "."))
        pn.append(f"{name}_p{j + 1}")
    cutrw = ", ".join(f"absorbFrom_cut _ _ _ {b[j - 1]} {b[j] - b[j - 1]} {N - b[j]} {N - b[j - 1]} {b[j]} (by omega) (by omega)"
                      for j in range(1, len(b)))
    # the cuts rewrite the outermost absorbFrom first: absorbFrom 0 N = absorbFrom b1 (N-b1) (absorbFrom 0 b1), then the outer one again
    proof = [f"rw [H_eq_absorbFrom {M} ({d}) {N} (by decide +kernel)]", "rw [" + cutrw + "]", "rw [" + ", ".join(pn[:-1]) + "]",
             f"exact {pn[-1]}"]
    return txt, proof

txt, pf = sponge("tr_lit", "Data.pkL", "64", 10, TR_CUTS, "tr", "Data.trL", "`H(pk, 64)`")
s += txt + thm_with("tr_lit", "Spec.H Data.pkL 64 = Data.trL", "`tr = H(pk, 64)`.", pf)
s += thm("kL_eq", "Spec.slice outL 96 32 = Data.kL", "`K`.")
s += thm("mu_lit", "Spec.H (Data.trL ++ [0, 0, 0]) 64 = Data.muL", "`μ = H(tr ‖ M′, 64)` for `M′ = 0 ‖ 0 ‖ [0]`.")
s += thm("rho2_lit", "Spec.H (Data.kL ++ List.replicate 32 0 ++ Data.muL) 64 = Data.rho2L", "`ρ″ = H(K ‖ rnd ‖ μ, 64)`.")
for r in range(4):
    s += thm(f"yb_{r}", f"Spec.H (Data.rho2L ++ IntegerToBytes (0 + {r}) 2) (32 * (1 + bitlen (Spec.ML_DSA_44.γ₁ - 1))) = Data.yb_{r}", f"The SHAKE256 bytes of `ExpandMask` row {r}.")
for r in range(4):
    s += thm(f"mask_{r}", f"RPoly.toZq (BitUnpackF Data.yb_{r} (Spec.ML_DSA_44.γ₁ - 1) Spec.ML_DSA_44.γ₁) = Pl Data.y_{r}", f"`y[{r}]` (`BitUnpack` with the fast unpacking).")
s += thm_with("wmv_lit", "Spec.MatrixVectorNTT Av Yhv = WMVv", "`Â ∘ NTT(y)` (Sign step 12).", mv_proof("Av", "Yhv", "WMVv", "yh"))
for i in range(4):
    s += thm(f"w1_lit_p{i}", f"(Pl Data.w_{i}).map (HighBits Spec.ML_DSA_44) = Rl Data.w1_{i}", f"`HighBits` of `w[{i}]`.")
s += thm_with("w1_lit", "Spec.HighBitsVec Spec.ML_DSA_44 Wv = W1v", "`w₁ = HighBits(w)`.",
              ["unfold Wv W1v", "exact HighBitsVec_v4 _ _ _ _ _ _ _ _ _ w1_lit_p0 w1_lit_p1 w1_lit_p2 w1_lit_p3"])
s += thm("w1b_lit", "w1EncodeF Spec.ML_DSA_44 W1v = Data.w1bL", "`w1Encode(w₁)` with the fast packing.")
txt, pf = sponge("ct_lit", "(Data.muL ++ Data.w1bL)", "Spec.ML_DSA_44.lam / 4", 7, CT_CUTS, "ct", "Data.ctL", "`H(μ ‖ w1Encode(w₁), λ/4)`")
s += txt + thm_with("ct_lit", "Spec.H (Data.muL ++ Data.w1bL) (Spec.ML_DSA_44.lam / 4) = Data.ctL", "`c̃ = H(μ ‖ w1Encode(w₁), λ/4)`.", pf)
s += thm("sib_lit", "Spec.SampleInBall Spec.ML_DSA_44 512 Data.ctL = some Cp", "`c = SampleInBall(c̃)`.")
files["TopWitnessMisc"] = s + END


if check:
    with tempfile.TemporaryDirectory() as tmp:
        bad = []
        for n, c in files.items():
            with open(os.path.join(tmp, n + ".lean"), "w") as f:
                f.write(c)
            path = f"Proofs/{n}.lean"
            if not os.path.exists(path) or not filecmp.cmp(os.path.join(tmp, n + ".lean"), path, shallow=False):
                bad.append(path)
        if bad:
            sys.exit("WITNESS STAGE CHECK FAIL: differs from the generator output: " + ", ".join(bad))
    print("WITNESS STAGE CHECK OK:", len(files), "stage modules match the generator")
else:
    for n, c in files.items():
        with open(f"Proofs/{n}.lean", "w") as f:
            f.write(c)
    print("wrote", list(files))
