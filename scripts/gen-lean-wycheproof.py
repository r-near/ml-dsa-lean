#!/usr/bin/env python3
"""Generate lean/SpecTests/WycheproofData.lean from the vendored Wycheproof ML-DSA vectors (tests/data/wycheproof).

Usage: python3 -I scripts/gen-lean-wycheproof.py [--sign N] [--output PATH]

Selection:
  verify: every case of every group of the three *_verify_test.json files (valid signatures, bad encodings, bad hints,
          norm violations, wrong lengths, over-long contexts, ...). The public key is stored once per group.
  sign:   every case of every *_sign_seed_test.json group that carries a message (valid signatures, hedged `rnd`, contexts
          of 0..255 bytes, the over-long-context case), i.e. all but the `mu`-only cases (flag `Internal`), which need an
          external-mu interface. Each group's seed and public key are stored once; the evaluator checks
          KeyGen_internal(seed) against the public key and then signs. With --sign N only the first N cases per group
          (plus every `Randomized` / `InvalidContext` case) are kept; the default 0 keeps all.
  noseed: the `InvalidPrivateKey` groups of the *_sign_noseed_test.json files (expanded secret key with an s1 or s2
          coefficient outside [-eta, eta]); the evaluator records what the specification does with them.
Standard library only. Hex strings are lower case.
"""
import argparse
import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SETS = ["44", "65", "87"]


def load(set_, kind):
    path = ROOT / "tests" / "data" / "wycheproof" / f"mldsa_{set_}_{kind}_test.json.gz"
    with gzip.open(path, "rt") as f:
        return json.load(f)


def lit(s):
    return json.dumps(s)


def hexs(s):
    return lit((s or "").lower())


def boolean(b):
    return "true" if b else "false"


HEADER = """/-!
# Wycheproof test data (generated by `scripts/gen-lean-wycheproof.py`; do not edit by hand)

Source: the vendored Wycheproof ML-DSA vectors in `tests/data/wycheproof` (see the README there). All byte strings are
lower-case hex. `verifyGroups` carry every case of the three `mldsa_*_verify_test.json` files; `signGroups` every
message-bearing case (not the `mu`-only ones) of the `mldsa_*_sign_seed_test.json` files with a 32-byte seed; `badKeyCases`
the `InvalidPrivateKey` cases of the `mldsa_*_sign_noseed_test.json` files.
-/

namespace SpecTests.Wycheproof

structure VerifyCase where
  tcId : Nat
  msg : String
  ctx : String
  sig : String
  /-- `true` iff the vector's result is `valid`. -/
  expected : Bool
  flags : String
  comment : String

structure VerifyGroup where
  set : String
  /-- Index of the group in its file. -/
  group : Nat
  pk : String
  cases : Array VerifyCase

structure SignCase where
  tcId : Nat
  msg : String
  ctx : String
  rnd : String
  /-- Expected signature (empty for invalid vectors). -/
  sig : String
  expected : Bool
  flags : String
  comment : String

structure SignGroup where
  set : String
  /-- Index of the group in its file. -/
  group : Nat
  seed : String
  /-- The group's public key (empty if the group has none). -/
  pk : String
  cases : Array SignCase

/-- A secret key (expanded skEncode bytes) that the vector marks invalid: s1 or s2 has a coefficient outside [-η, η]. -/
structure BadKeyCase where
  set : String
  tcId : Nat
  sk : String
  msg : String
  ctx : String
  flags : String
  comment : String
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sign", type=int, default=0)
    ap.add_argument("--output", default=str(ROOT / "lean" / "SpecTests" / "WycheproofData.lean"))
    a = ap.parse_args()

    out = [HEADER]

    groups = []
    n_verify = 0
    for set_ in SETS:
        d = load(set_, "verify")
        for gi, g in enumerate(d["testGroups"]):
            cases = []
            for t in g["tests"]:
                n_verify += 1
                cases.append(
                    f"    {{ tcId := {int(t['tcId'])}, msg := {hexs(t.get('msg'))}, ctx := {hexs(t.get('ctx'))},"
                    f" sig := {hexs(t.get('sig'))}, expected := {boolean(t['result'] == 'valid')},"
                    f" flags := {lit(','.join(t['flags']))}, comment := {lit(t['comment'])} }}"
                )
            groups.append(
                f"  {{ set := \"ML-DSA-{set_}\", group := {gi}, pk := {hexs(g['publicKey'])}, cases := #[\n"
                + ",\n".join(cases)
                + "] }"
            )
    out.append("def verifyGroups : Array VerifyGroup := #[")
    out.append(",\n".join(groups) + "]\n")

    sgroups = []
    n_sign = 0
    for set_ in SETS:
        d = load(set_, "sign_seed")
        for gi, g in enumerate(d["testGroups"]):
            cases = []
            kept = 0
            for t in g["tests"]:
                if t.get("msg") is None:
                    continue  # mu-only case (flag Internal)
                special = "Randomized" in t["flags"] or "InvalidContext" in t["flags"]
                if a.sign and kept >= a.sign and not special:
                    continue
                kept += 1
                cases.append(
                    f"    {{ tcId := {int(t['tcId'])}, msg := {hexs(t['msg'])}, ctx := {hexs(t.get('ctx'))},"
                    f" rnd := {hexs(t.get('rnd') or '00' * 32)}, sig := {hexs(t.get('sig'))},"
                    f" expected := {boolean(t['result'] == 'valid')}, flags := {lit(','.join(t['flags']))},"
                    f" comment := {lit(t['comment'])} }}"
                )
            if not cases or len(g["privateSeed"]) != 64:
                continue  # also drops the wrong-seed-length IncorrectPrivateKeyLength groups
            n_sign += len(cases)
            sgroups.append(
                f"  {{ set := \"ML-DSA-{set_}\", group := {gi}, seed := {hexs(g['privateSeed'])},"
                f" pk := {hexs(g.get('publicKey'))}, cases := #[\n" + ",\n".join(cases) + "] }"
            )
    out.append("def signGroups : Array SignGroup := #[")
    out.append(",\n".join(sgroups) + "]\n")

    bad = []
    for set_ in SETS:
        d = load(set_, "sign_noseed")
        for g in d["testGroups"]:
            for t in g["tests"]:
                if "InvalidPrivateKey" in t["flags"]:
                    bad.append(
                        f"  {{ set := \"ML-DSA-{set_}\", tcId := {int(t['tcId'])}, sk := {hexs(g['privateKey'])},"
                        f" msg := {hexs(t.get('msg'))}, ctx := {hexs(t.get('ctx'))}, flags := {lit(','.join(t['flags']))},"
                        f" comment := {lit(t['comment'])} }}"
                    )
    out.append("def badKeyCases : Array BadKeyCase := #[")
    out.append(",\n".join(bad) + "]\n")
    out.append("end SpecTests.Wycheproof\n")

    Path(a.output).write_text("\n".join(out))
    print(f"wrote {a.output}: {n_verify} verify cases in {len(groups)} groups, {n_sign} sign cases in {len(sgroups)} groups, {len(bad)} bad-key cases", file=sys.stderr)


if __name__ == "__main__":
    main()
