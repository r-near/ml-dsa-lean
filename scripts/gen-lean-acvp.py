#!/usr/bin/env python3
"""Generate lean/SpecTests/ACVPData.lean from the vendored ACVP ML-DSA vectors (tests/data/acvp).

Usage: python3 -I scripts/gen-lean-acvp.py [--keygen N] [--siggen N] [--output PATH]

Selection (pure ML-DSA only; preHash and externalMu groups need HashML-DSA / external mu, out of scope):
  keyGen: the first N cases of each parameter set (default 3).
  sigGen: the first N cases of each pure group (default 2): per parameter set, internal and external
          interface, deterministic and hedged.
  sigVer: every case of every pure, non-externalMu group (valid signatures and all failure modes).
Standard library only. Hex strings are lower case.
"""
import argparse
import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(name):
    with gzip.open(ROOT / "tests" / "data" / "acvp" / f"{name}.json.gz", "rt") as f:
        return json.load(f)


def lit(s):
    return json.dumps(s)


def hexs(s):
    return lit(s.lower()) if s is not None else lit("")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--keygen", type=int, default=3)
    ap.add_argument("--siggen", type=int, default=2)
    ap.add_argument("--output", default=str(ROOT / "lean" / "SpecTests" / "ACVPData.lean"))
    a = ap.parse_args()

    out = []
    out.append("""/-!
# ACVP test data (generated by `scripts/gen-lean-acvp.py`; do not edit by hand)

Source: the vendored NIST ACVP ML-DSA vectors in `tests/data/acvp` (see the README there). Only pure ML-DSA
(no preHash, no externalMu) cases are included. All byte strings are lower-case hex.
-/

namespace SpecTests.ACVP

structure KeyGenCase where
  set : String
  tcId : Nat
  seed : String
  pk : String
  sk : String

structure SigGenCase where
  set : String
  tcId : Nat
  /-- `"internal"`: `message` is M′; `"external"`: `message` is M and `context` the context string. -/
  interface : String
  deterministic : Bool
  sk : String
  message : String
  context : String
  rnd : String
  signature : String

structure SigVerCase where
  set : String
  tcId : Nat
  interface : String
  pk : String
  message : String
  context : String
  signature : String
  expected : Bool
  reason : String
""")

    kg = load("keyGen")
    out.append("def keyGenCases : Array KeyGenCase := #[")
    rows = []
    for g in kg["testGroups"]:
        for t in g["tests"][: a.keygen]:
            rows.append(
                f"  {{ set := {lit(g['parameterSet'])}, tcId := {int(t['tcId'])}, seed := {hexs(t['seed'])},"
                f" pk := {hexs(t['pk'])}, sk := {hexs(t['sk'])} }}"
            )
    out.append(",\n".join(rows) + "]\n")

    sg = load("sigGen")
    rows = []
    for g in sg["testGroups"]:
        if g["externalMu"] or g["preHash"] == "preHash":
            continue
        det = bool(g["deterministic"])
        for t in g["tests"][: a.siggen]:
            msg = t["message"]
            ctx = t.get("context", "") if g["signatureInterface"] == "external" else ""
            rnd = "00" * 32 if det else t["rnd"]
            rows.append(
                f"  {{ set := {lit(g['parameterSet'])}, tcId := {int(t['tcId'])},"
                f" interface := {lit(g['signatureInterface'])}, deterministic := {'true' if det else 'false'},"
                f" sk := {hexs(t['sk'])}, message := {hexs(msg)}, context := {hexs(ctx)}, rnd := {hexs(rnd)},"
                f" signature := {hexs(t['signature'])} }}"
            )
    out.append("def sigGenCases : Array SigGenCase := #[")
    out.append(",\n".join(rows) + "]\n")

    sv = load("sigVer")
    rows = []
    for g in sv["testGroups"]:
        if g["externalMu"] or g["preHash"] == "preHash":
            continue
        for t in g["tests"]:
            ctx = t.get("context", "") if g["signatureInterface"] == "external" else ""
            rows.append(
                f"  {{ set := {lit(g['parameterSet'])}, tcId := {int(t['tcId'])},"
                f" interface := {lit(g['signatureInterface'])}, pk := {hexs(t['pk'])},"
                f" message := {hexs(t['message'])}, context := {hexs(ctx)}, signature := {hexs(t['signature'])},"
                f" expected := {'true' if t['testPassed'] else 'false'}, reason := {lit(t.get('reason', ''))} }}"
            )
    out.append("def sigVerCases : Array SigVerCase := #[")
    out.append(",\n".join(rows) + "]\n")
    out.append("end SpecTests.ACVP\n")

    Path(a.output).write_text("\n".join(out))
    print(f"wrote {a.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
