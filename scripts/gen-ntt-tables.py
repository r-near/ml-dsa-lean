#!/usr/bin/env python3
"""Generate (or check) the Shoup companion tables in src/ntt.rs from its ZETAS table.

Usage: python3 -I scripts/gen-ntt-tables.py [--check]
  default  rewrite the generated block of src/ntt.rs (between the BEGIN/END GENERATED markers)
  --check  exit 1 if the block in src/ntt.rs differs from what would be generated

The tables are not trusted: lean/Proofs/NTTTables.lean proves each entry by `decide +kernel`
(ZETAS_SHOUP[k] = ZETAS[k] * 2^32 / q, ZETAS_NEG_SHOUP[k] = (q - ZETAS[k]) * 2^32 / q, F_SHOUP likewise).
"""
import re
import sys
from pathlib import Path

Q = 8380417
path = Path(__file__).resolve().parent.parent / "src/ntt.rs"
text = path.read_text()
zbody = re.search(r"pub const ZETAS: \[u32; 256\] = \[(.*?)\];", text, re.S).group(1)
Z = [int(x) for x in re.findall(r"\d+", zbody)]
assert len(Z) == 256 and all(0 < z < Q for z in Z)
F = 8_347_681  # 256^-1 mod q
assert F * 256 % Q == 1


def table(name, doc, vals):
    rows = []
    line = "   "
    for v in vals:
        item = f" {v},"
        if len(line) + len(item) > 118:
            rows.append(line)
            line = "   "
        line += item
    rows.append(line)
    return f"/// {doc}\npub const {name}: [u32; 256] = [\n" + "\n".join(rows) + "\n];\n"


block = (
    table("ZETAS_SHOUP", "Shoup companions floor(ZETAS[k] * 2^32 / q) (generated by scripts/gen-ntt-tables.py).",
          [(z << 32) // Q for z in Z])
    + "\n"
    + table("ZETAS_NEG_SHOUP",
            "Shoup companions floor((q - ZETAS[k]) * 2^32 / q) of the negated twiddles of NTT^-1.",
            [((Q - z) << 32) // Q for z in Z])
    + f"\n/// Shoup companion floor(F * 2^32 / q) of F = 256^-1 mod q.\npub const F_SHOUP: u32 = {(F << 32) // Q};\n"
)
begin, end = "// BEGIN GENERATED (scripts/gen-ntt-tables.py)\n", "// END GENERATED\n"
if begin not in text:
    sys.exit("markers missing in src/ntt.rs")
head, rest = text.split(begin)
_, tail = rest.split(end)
new = head + begin + block + end + tail
if "--check" in sys.argv:
    sys.exit(0 if new == text else 1)
path.write_text(new)
print("updated", path)
