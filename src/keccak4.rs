//! 4-way Keccak-f[1600]: four independent states permuted at once, written once against a trait of lane-wise
//! operations (`Lanes4`) and instantiated twice.
//!
//! * `Shim4`: plain Rust over `[u64; 4]`. This is the instantiation Charon/Aeneas see and the one portable builds run.
//! * `avx2::Avx2` (feature `avx2`, x86_64, not Miri): the same operations as AVX2 intrinsics. Outside the Lean proof.
//!
//! State layout: `s[k]` is lane `k = x + 5y` of all four states, `s[k][i]` is lane `k` of state `i`.
//! Every operation works on whole `[u64; 4]` values (lane `i` of the result depends on lane `i` of the arguments
//! only), so the kernel is data independent and has no control flow beyond the 24-round loop.

use crate::keccak::RC;

/// Lane-wise operations on four `u64` lanes. Lane `i` of every result is a function of lane `i` of the arguments.
pub trait Lanes4 {
    /// `a ^ b`.
    fn xor(a: [u64; 4], b: [u64; 4]) -> [u64; 4];
    /// `!a & b` (the operand order of `_mm256_andnot_si256`).
    fn andnot(a: [u64; 4], b: [u64; 4]) -> [u64; 4];
    /// Rotate each lane left by `L`; `R` must be `64 - L` and `0 < L < 64`.
    fn rotl<const L: u32, const R: u32>(a: [u64; 4]) -> [u64; 4];
    /// `[x; 4]`.
    fn splat(x: u64) -> [u64; 4];
}

/// The plain-Rust model of the operations: what extraction sees, and what portable builds run.
pub struct Shim4;

impl Lanes4 for Shim4 {
    #[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64"), inline(always))]
    fn xor(a: [u64; 4], b: [u64; 4]) -> [u64; 4] {
        [a[0] ^ b[0], a[1] ^ b[1], a[2] ^ b[2], a[3] ^ b[3]]
    }
    #[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64"), inline(always))]
    fn andnot(a: [u64; 4], b: [u64; 4]) -> [u64; 4] {
        [!a[0] & b[0], !a[1] & b[1], !a[2] & b[2], !a[3] & b[3]]
    }
    #[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64"), inline(always))]
    fn rotl<const L: u32, const R: u32>(a: [u64; 4]) -> [u64; 4] {
        [
            (a[0] << L) | (a[0] >> R),
            (a[1] << L) | (a[1] >> R),
            (a[2] << L) | (a[2] >> R),
            (a[3] << L) | (a[3] >> R),
        ]
    }
    #[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64"), inline(always))]
    fn splat(x: u64) -> [u64; 4] {
        [x, x, x, x]
    }
}

/// One Keccak-f[1600] round (θ, ρ, π, χ, ι with round constant `rc`) on the four states, unrolled. Generated by
/// `scripts/gen_keccak4_round.py`; the operations and their association order are those of `keccak::keccak_f1600`
/// (ρ is fused with the θ xor: `rotl(a ^ d)` is the scalar's `a ^= d` followed by the ρ rotation).
#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64"), inline(always))]
fn round<L: Lanes4>(s: &mut [[u64; 4]; 25], rc: u64) {
    let a0 = s[0];
    let a1 = s[1];
    let a2 = s[2];
    let a3 = s[3];
    let a4 = s[4];
    let a5 = s[5];
    let a6 = s[6];
    let a7 = s[7];
    let a8 = s[8];
    let a9 = s[9];
    let a10 = s[10];
    let a11 = s[11];
    let a12 = s[12];
    let a13 = s[13];
    let a14 = s[14];
    let a15 = s[15];
    let a16 = s[16];
    let a17 = s[17];
    let a18 = s[18];
    let a19 = s[19];
    let a20 = s[20];
    let a21 = s[21];
    let a22 = s[22];
    let a23 = s[23];
    let a24 = s[24];
    let c0 = L::xor(L::xor(L::xor(L::xor(a0, a5), a10), a15), a20);
    let c1 = L::xor(L::xor(L::xor(L::xor(a1, a6), a11), a16), a21);
    let c2 = L::xor(L::xor(L::xor(L::xor(a2, a7), a12), a17), a22);
    let c3 = L::xor(L::xor(L::xor(L::xor(a3, a8), a13), a18), a23);
    let c4 = L::xor(L::xor(L::xor(L::xor(a4, a9), a14), a19), a24);
    let d0 = L::xor(c4, L::rotl::<1, 63>(c1));
    let d1 = L::xor(c0, L::rotl::<1, 63>(c2));
    let d2 = L::xor(c1, L::rotl::<1, 63>(c3));
    let d3 = L::xor(c2, L::rotl::<1, 63>(c4));
    let d4 = L::xor(c3, L::rotl::<1, 63>(c0));
    let b0 = L::xor(a0, d0);
    let b16 = L::rotl::<36, 28>(L::xor(a5, d0));
    let b7 = L::rotl::<3, 61>(L::xor(a10, d0));
    let b23 = L::rotl::<41, 23>(L::xor(a15, d0));
    let b14 = L::rotl::<18, 46>(L::xor(a20, d0));
    let b10 = L::rotl::<1, 63>(L::xor(a1, d1));
    let b1 = L::rotl::<44, 20>(L::xor(a6, d1));
    let b17 = L::rotl::<10, 54>(L::xor(a11, d1));
    let b8 = L::rotl::<45, 19>(L::xor(a16, d1));
    let b24 = L::rotl::<2, 62>(L::xor(a21, d1));
    let b20 = L::rotl::<62, 2>(L::xor(a2, d2));
    let b11 = L::rotl::<6, 58>(L::xor(a7, d2));
    let b2 = L::rotl::<43, 21>(L::xor(a12, d2));
    let b18 = L::rotl::<15, 49>(L::xor(a17, d2));
    let b9 = L::rotl::<61, 3>(L::xor(a22, d2));
    let b5 = L::rotl::<28, 36>(L::xor(a3, d3));
    let b21 = L::rotl::<55, 9>(L::xor(a8, d3));
    let b12 = L::rotl::<25, 39>(L::xor(a13, d3));
    let b3 = L::rotl::<21, 43>(L::xor(a18, d3));
    let b19 = L::rotl::<56, 8>(L::xor(a23, d3));
    let b15 = L::rotl::<27, 37>(L::xor(a4, d4));
    let b6 = L::rotl::<20, 44>(L::xor(a9, d4));
    let b22 = L::rotl::<39, 25>(L::xor(a14, d4));
    let b13 = L::rotl::<8, 56>(L::xor(a19, d4));
    let b4 = L::rotl::<14, 50>(L::xor(a24, d4));
    s[0] = L::xor(L::xor(b0, L::andnot(b1, b2)), L::splat(rc));
    s[5] = L::xor(b5, L::andnot(b6, b7));
    s[10] = L::xor(b10, L::andnot(b11, b12));
    s[15] = L::xor(b15, L::andnot(b16, b17));
    s[20] = L::xor(b20, L::andnot(b21, b22));
    s[1] = L::xor(b1, L::andnot(b2, b3));
    s[6] = L::xor(b6, L::andnot(b7, b8));
    s[11] = L::xor(b11, L::andnot(b12, b13));
    s[16] = L::xor(b16, L::andnot(b17, b18));
    s[21] = L::xor(b21, L::andnot(b22, b23));
    s[2] = L::xor(b2, L::andnot(b3, b4));
    s[7] = L::xor(b7, L::andnot(b8, b9));
    s[12] = L::xor(b12, L::andnot(b13, b14));
    s[17] = L::xor(b17, L::andnot(b18, b19));
    s[22] = L::xor(b22, L::andnot(b23, b24));
    s[3] = L::xor(b3, L::andnot(b4, b0));
    s[8] = L::xor(b8, L::andnot(b9, b5));
    s[13] = L::xor(b13, L::andnot(b14, b10));
    s[18] = L::xor(b18, L::andnot(b19, b15));
    s[23] = L::xor(b23, L::andnot(b24, b20));
    s[4] = L::xor(b4, L::andnot(b0, b1));
    s[9] = L::xor(b9, L::andnot(b5, b6));
    s[14] = L::xor(b14, L::andnot(b10, b11));
    s[19] = L::xor(b19, L::andnot(b15, b16));
    s[24] = L::xor(b24, L::andnot(b20, b21));
}

/// Keccak-f[1600] on four states at once, lane `i` of every `s[k]` being state `i`.
#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64"), inline(always))]
pub fn keccak_f1600_x4<L: Lanes4>(s: &mut [[u64; 4]; 25]) {
    let mut r = 0;
    while r < 24 {
        round::<L>(s, RC[r]);
        r += 1;
    }
}

/// The portable instantiation: `keccak_f1600_x4` over `Shim4`.
pub fn keccak_f1600_x4_portable(s: &mut [[u64; 4]; 25]) {
    keccak_f1600_x4::<Shim4>(s)
}

/// The AVX2 instantiation. Outside the Lean proof; see the module docs.
#[cfg(all(feature = "avx2", not(miri), target_arch = "x86_64"))]
#[allow(unsafe_code)]
pub mod avx2 {
    use super::{Lanes4, keccak_f1600_x4};
    use core::arch::x86_64::{
        __m256i, _mm_cvtsi32_si128, _mm256_andnot_si256, _mm256_loadu_si256, _mm256_or_si256, _mm256_set1_epi64x,
        _mm256_sll_epi64, _mm256_srl_epi64, _mm256_storeu_si256, _mm256_xor_si256,
    };

    /// The AVX2 operations. Only sound to call from code compiled with AVX2 enabled and run on a CPU that has it,
    /// which is why the type is only reachable through `keccak_f1600_x4_avx2` (and the tests).
    pub struct Avx2;

    // SAFETY (all of `ld`, `st` and the trait methods): every use is inlined into a function compiled with
    // `#[target_feature(enable = "avx2")]`; the loads and stores are of exactly 32 bytes from/to a `[u64; 4]`.
    #[inline(always)]
    fn ld(a: &[u64; 4]) -> __m256i {
        unsafe { _mm256_loadu_si256(a.as_ptr().cast()) }
    }
    #[inline(always)]
    fn st(v: __m256i) -> [u64; 4] {
        let mut r = [0u64; 4];
        unsafe { _mm256_storeu_si256(r.as_mut_ptr().cast(), v) };
        r
    }

    impl Lanes4 for Avx2 {
        #[inline(always)]
        fn xor(a: [u64; 4], b: [u64; 4]) -> [u64; 4] {
            st(unsafe { _mm256_xor_si256(ld(&a), ld(&b)) })
        }
        #[inline(always)]
        fn andnot(a: [u64; 4], b: [u64; 4]) -> [u64; 4] {
            st(unsafe { _mm256_andnot_si256(ld(&a), ld(&b)) })
        }
        #[inline(always)]
        fn rotl<const L: u32, const R: u32>(a: [u64; 4]) -> [u64; 4] {
            // The variable-count shifts take the count in an xmm register; with L and R constants after inlining
            // LLVM emits the immediate forms.
            let v = ld(&a);
            st(unsafe {
                _mm256_or_si256(
                    _mm256_sll_epi64(v, _mm_cvtsi32_si128(L as i32)),
                    _mm256_srl_epi64(v, _mm_cvtsi32_si128(R as i32)),
                )
            })
        }
        #[inline(always)]
        fn splat(x: u64) -> [u64; 4] {
            st(unsafe { _mm256_set1_epi64x(x as i64) })
        }
    }

    /// Keccak-f[1600] on four states with AVX2. Safe to define, `unsafe` to call without checking for AVX2.
    #[target_feature(enable = "avx2")]
    pub fn keccak_f1600_x4_avx2(s: &mut [[u64; 4]; 25]) {
        keccak_f1600_x4::<Avx2>(s)
    }
}
