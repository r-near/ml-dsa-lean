#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64", not(target_feature = "avx2")), inline(always))]
fn ntt_layer<const LEN: usize, const ITERATIONS: usize>(w: &mut [u32; 256], m: &mut usize) {
    let mut i = 0;
    while i < ITERATIONS {
        let start = i * 2 * LEN;
        *m += 1;
        let z = ZETAS[*m];
        let zp = ZETAS_SHOUP[*m];
        let mut j = start;
        while j < (start + LEN) {
            let t = mul_shoup(z, zp, w[j + LEN]);
            w[j + LEN] = sub(w[j], t);
            w[j] = add(w[j], t);
            j += 1;
        }
        i += 1;
    }
}

#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64", not(target_feature = "avx2")), inline(always))]
fn ntt_inverse_layer<const LEN: usize, const ITERATIONS: usize>(w: &mut [u32; 256], m: &mut usize) {
    let mut i = 0;
    while i < ITERATIONS {
        let start = i * 2 * LEN;
        *m -= 1;
        let z = sub(0, ZETAS[*m]);
        let zp = ZETAS_NEG_SHOUP[*m];
        let mut j = start;
        while j < (start + LEN) {
            let t = w[j];
            w[j] = add(t, w[j + LEN]);
            w[j + LEN] = mul_shoup(z, zp, sub(t, w[j + LEN]));
            j += 1;
        }
        i += 1;
    }
}

/// Algorithm 41 NTT(w) in place, the shared body (see "Dispatch" below).
#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64", not(target_feature = "avx2")), inline(always))]
fn ntt_body_mut(w: &mut [u32; 256]) {
    let mut m = 0;
    ntt_layer::<128, 1>(w, &mut m);
    ntt_layer::<64, 2>(w, &mut m);
    ntt_layer::<32, 4>(w, &mut m);
    ntt_layer::<16, 8>(w, &mut m);
    ntt_layer::<8, 16>(w, &mut m);
    ntt_layer::<4, 32>(w, &mut m);
    ntt_layer::<2, 64>(w, &mut m);
    ntt_layer::<1, 128>(w, &mut m);
}

/// Algorithm 41 NTT(w), the shared body: a copy of `w`, transformed in place.
#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64", not(target_feature = "avx2")), inline(always))]
fn ntt_body(w: &[u32; 256]) -> [u32; 256] {
    let mut o = *w;
    ntt_body_mut(&mut o);
    o
}

/// Algorithm 42 NTT⁻¹(ŵ), the shared body.
#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64", not(target_feature = "avx2")), inline(always))]
fn ntt_inverse_body(w_hat: &[u32; 256]) -> [u32; 256] {
    let mut w = *w_hat;
    let mut m = 256;
    ntt_inverse_layer::<1, 128>(&mut w, &mut m);
    ntt_inverse_layer::<2, 64>(&mut w, &mut m);
    ntt_inverse_layer::<4, 32>(&mut w, &mut m);
    ntt_inverse_layer::<8, 16>(&mut w, &mut m);
    ntt_inverse_layer::<16, 8>(&mut w, &mut m);
    ntt_inverse_layer::<32, 4>(&mut w, &mut m);
    ntt_inverse_layer::<64, 2>(&mut w, &mut m);
    ntt_inverse_layer::<128, 1>(&mut w, &mut m);
    let f = 8_347_681; // 256⁻¹ mod q
    let mut j = 0;
    while j < 256 {
        w[j] = mul_shoup(f, F_SHOUP, w[j]);
        j += 1;
    }
    w
}

/// Algorithm 45 MultiplyNTT(â, b̂), the shared body.
#[cfg_attr(all(feature = "avx2", not(miri), target_arch = "x86_64", not(target_feature = "avx2")), inline(always))]
fn multiply_ntt_body(a: &[u32; 256], b: &[u32; 256]) -> [u32; 256] {
    let mut c = [0u32; 256];
    let mut i = 0;
    while i < 256 {
        c[i] = mul_mont(a[i], b[i]);
        i += 1;
    }
    c
}

